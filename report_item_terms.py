def _norm(text):
    import re
    s = str(text or '')
    s = re.sub(r'[（(][^）)]*[）)]', '', s)
    return re.sub(r'\s+', '', s)


_TOTAL_KEYS = {_norm(k) for k in TOTALS}
_SUB_KEYS = {_norm(k): v for k, v in SUB_ITEMS.items()}


def is_total(name):
    """是不是合计项。"""
    return _norm(name) in _TOTAL_KEYS


def parent_of(name):
    """如果是某项目的子项，返回母项名；否则 None。"""
    return _SUB_KEYS.get(_norm(name))


def children_of(name):
    """合计项的子项列表。"""
    n = _norm(name)
    for k, v in TOTALS.items():
        if _norm(k) == n:
            return v
    return []


def is_line_item(name):
    """真正的报表项目：不是合计项、也不是别人的子项。"""
    return not is_total(name) and parent_of(name) is None
